-- 2. Crear la tabla GENERO
CREATE TABLE GENERO (
    ID_CATEGORIA NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(100)
);

CREATE SEQUENCE SEQ_GENERO 
START WITH 1 
INCREMENT BY 1;

CREATE OR REPLACE TRIGGER TRG_BI_GENERO
BEFORE INSERT ON GENERO
FOR EACH ROW
BEGIN
    IF :NEW.ID_CATEGORIA IS NULL THEN
        SELECT SEQ_GENERO.NEXTVAL INTO :NEW.ID_CATEGORIA FROM DUAL;
    END IF;
END;
/


-- 3. Crear la tabla VIDEO_JUEGOS
CREATE TABLE VIDEO_JUEGOS (
    ID_VIDEO NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    ID_CATEGORIA NUMBER NOT NULL,
    CONSTRAINT FK_VIDEO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES GENERO(ID_CATEGORIA)
);

CREATE SEQUENCE SEQ_VIDEO_JUEGOS 
START WITH 1 
INCREMENT BY 1;

CREATE OR REPLACE TRIGGER TRG_BI_VIDEO_JUEGOS
BEFORE INSERT ON VIDEO_JUEGOS
FOR EACH ROW
BEGIN
    IF :NEW.ID_VIDEO IS NULL THEN
        SELECT SEQ_VIDEO_JUEGOS.NEXTVAL INTO :NEW.ID_VIDEO FROM DUAL;
    END IF;
END;
/

